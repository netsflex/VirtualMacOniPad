#!/usr/bin/env python3
"""Turn a device identity probe capture into a persistent cache receipt.

Reads the JSON printed by persistent-cache-identity-probe.py, checks it against
the compiler table compiled into modern_pvg_shader_persistent.inc, and writes
persistent-cache-identity-v1.json plus a matching persistent_cache_identity.h
into a new output directory. Nothing is deployed and the source tree is not
modified; copy the header into a build copy of vz/host before rebuilding Task.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "vz/host/modern_pvg_shader_persistent.inc"
STAT_KEYS = (
    "dev", "ino", "size", "uid", "gid", "nlink", "mode", "flags", "gen", "rdev",
    "blocks", "blksize", "mtimeSec", "mtimeNsec", "ctimeSec", "ctimeNsec",
    "birthSec", "birthNsec",
)


def fail(message):
    raise SystemExit("error: " + message)


def compiled_expectations():
    text = SOURCE.read_text()
    table = re.findall(r'\{"([^"]+)","([0-9a-f]{64})","([0-9a-f]{40})",(\d+)\}', text)
    profile = re.search(r'compilerProfileSHA256"\] isEqual:@"([0-9a-f]{64})"', text)
    profile_file = re.search(r'compilerProfileFileSHA256"\] isEqual:@"([0-9a-f]{64})"', text)
    if len(table) != 7 or not profile or not profile_file:
        fail("could not read the compiler table from " + str(SOURCE))
    return table, profile.group(1), profile_file.group(1)


def checked_stat(name, value):
    if not isinstance(value, dict) or set(value) != set(STAT_KEYS):
        fail(name + ": incomplete stat capture")
    for key in STAT_KEYS:
        if isinstance(value[key], bool) or not isinstance(value[key], int) or value[key] < 0:
            fail(f"{name}: stat field {key} is not a non-negative integer")
    # The task accepts only root:wheel 0755 single-link regular files.
    if (value["uid"], value["gid"], value["nlink"], value["mode"]) != (0, 0, 1, 0o100755):
        fail(name + ": owner, link count or mode is not root:wheel 0755")
    return {key: value[key] for key in STAT_KEYS}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("capture", type=Path, help="probe output captured as mobile")
    parser.add_argument("output", type=Path, help="new directory for the receipt and header")
    arguments = parser.parse_args()

    capture = json.loads(arguments.capture.read_text())
    if capture.get("uid") != 501:
        fail("the capture was not taken as mobile (uid 501)")
    table, profile_hash, profile_file_hash = compiled_expectations()
    if capture.get("profile", {}).get("sha256") != profile_file_hash:
        fail("compiler-profile.json does not match the compiled profile hash")
    rows = capture.get("files")
    if not isinstance(rows, list) or len(rows) != len(table):
        fail("the capture does not list exactly seven compiler files")

    files = []
    for row, (name, sha, cdhash, size) in zip(rows, table):
        if row.get("filename") != name or row.get("sha256") != sha:
            fail(name + ": filename or SHA256 differs from the compiled table")
        stat = checked_stat(name, row.get("stat"))
        if stat["size"] != int(size):
            fail(name + ": size differs from the compiled table")
        files.append({"filename": name, "sha256": sha, "cdhash": cdhash,
                      "size": int(size), "stat": stat})

    receipt = json.dumps({
        "formatVersion": 1,
        "compilerProfileSHA256": profile_hash,
        "compilerProfileFileSHA256": profile_file_hash,
        "deviceSystemModified": False,
        "files": files,
    }, sort_keys=True, separators=(",", ":")).encode() + b"\n"
    digest = hashlib.sha256(receipt).hexdigest()

    arguments.output.mkdir(parents=True, exist_ok=False)
    (arguments.output / "persistent-cache-identity-v1.json").write_bytes(receipt)
    (arguments.output / "persistent_cache_identity.h").write_text(
        "#pragma once\n"
        "// Generated by make-persistent-cache-receipt.py for one device capture.\n"
        "// Identity/stat mismatch leaves the original dynamic conversion path intact.\n"
        f'#define VZ_PERSISTENT_RECEIPT_SHA256 "{digest}"\n')
    print(digest)


if __name__ == "__main__":
    sys.exit(main())
